function unavailableMessage(label: string, source: SecretReentrySource): string {
    return source === 'publish'
        ? `The staged changes send ${label} to a new address and need it entered again, which isn't possible here. Discard the draft and make the change in the form.`
        : `Enter ${label} again in the form. Your edits send this secret to a new address.`
}

function trackingProperties(prompt: SecretReentryPrompt): Record<string, string> {
    return { source: prompt.source, kind: prompt.entryKeys ? 'dictionary' : 'single' }
}

