/** The state of the dialog that asks for a refused secret again. The logic that opens it decides what confirming does. */
export const secretReentryDialogLogic = kea<secretReentryDialogLogicType>([
    props({} as SecretReentryDialogLogicProps),
    key((props) => props.dialogKey),
    path((key) => ['scenes', 'hog-functions', 'configuration', 'secretReentryDialogLogic', key]),
    actions({
        // `currentInput` is the refused input as the asked configuration holds it, which keeps a dictionary's unmasked entries.
        openSecretReentry: (prompt: SecretReentryPrompt, currentInput?: CyclotronJobInputType) => ({
            prompt,
            currentInput,
        }),
        setSecretValue: (value: string) => ({ value }),
        setSecretEntry: (entryKey: string, value: string) => ({ entryKey, value }),
        cancelSecretReentry: true,
        confirmSecretReentry: true,
        closeSecretReentry: true,
        clearSecretReentry: true,
    }),
    reducers({
        isOpen: [
            false,
            {
                openSecretReentry: () => true,
                closeSecretReentry: () => false,
            },
        ],
        // Kept after close until the modal has animated out, so the closing dialog does not change its content.
        prompt: [
            null as SecretReentryPrompt | null,
            {
                openSecretReentry: (_, { prompt }) => prompt,
                clearSecretReentry: () => null,
            },
        ],
        currentInput: [
            null as CyclotronJobInputType | null,
            {
                openSecretReentry: (_, { currentInput }) => currentInput ?? null,
                clearSecretReentry: () => null,
            },
        ],
        secretValue: [
            '',
            {
                setSecretValue: (_, { value }) => value,
                openSecretReentry: () => '',
                clearSecretReentry: () => '',
            },
        ],
        secretEntryValues: [
            {} as Record<string, string>,
            {
                setSecretEntry: (state, { entryKey, value }) => ({ ...state, [entryKey]: value }),
                openSecretReentry: () => ({}),
                clearSecretReentry: () => ({}),
            },
        ],
    }),
    selectors({
        confirmDisabledReason: [
            (s) => [s.prompt, s.secretValue, s.secretEntryValues],
            (
                prompt: SecretReentryPrompt | null,
                secretValue: string,
                secretEntryValues: Record<string, string>
            ): string | undefined => {
                if (!prompt) {
                    return undefined
                }
                if (prompt.entryKeys) {
                    return prompt.entryKeys.every((entry) => secretEntryValues[entry]?.trim())
                        ? undefined
                        : 'Enter every value'
                }
                return secretValue.trim() ? undefined : 'Enter the secret'
            },
        ],
        // What the user entered, ready to store, or null while the dialog cannot be confirmed.
        enteredValue: [
            (s) => [s.prompt, s.currentInput, s.secretValue, s.secretEntryValues, s.confirmDisabledReason],
            (
                prompt: SecretReentryPrompt | null,
                currentInput: CyclotronJobInputType | null,
                secretValue: string,
                secretEntryValues: Record<string, string>,
                confirmDisabledReason: string | undefined
            ): SecretReentryValue | null => {
                if (!prompt || confirmDisabledReason) {
                    return null
                }
                return prompt.entryKeys
                    ? { ...textEntries(currentInput ?? undefined), ...secretEntryValues }
                    : secretValue
            },
        ],
    }),
])
