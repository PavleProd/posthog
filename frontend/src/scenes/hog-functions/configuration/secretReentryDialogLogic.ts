import { MASKED_SECRET_VALUE, secretEntries } from 'lib/components/CyclotronJob/dictionarySecretRows'

import type { CyclotronJobInputSchemaType, CyclotronJobInputType } from '~/types'

import { InputRefusal } from './inputRefusal'

// Save and test send the form, so the entered secret goes into the form. A hog function's publish sends the
// staged draft, which the form does not hold, so the entered secret goes with the publish request instead.
export type SecretReentrySource = 'save' | 'test' | 'publish'

export interface SecretReentryConfiguration {
    inputs_schema?: CyclotronJobInputSchemaType[] | null
    inputs?: Record<string, CyclotronJobInputType> | null
}

export type SecretReentryValue = string | Record<string, string>

export type EnteredSecretInputs = Record<string, { value: SecretReentryValue }>

export interface SecretReentryPrompt {
    key: string
    label: string
    // The server's reason for the refusal, which names the hosts the change sends the secret to.
    detail: string
    // The masked entries of a dictionary secret, each of which has to be typed again. Null for a single value.
    entryKeys: string[] | null
    source: SecretReentrySource
}

export interface SecretReentryDialogLogicProps {
    dialogKey: string
}

export function textEntries(input: CyclotronJobInputType | undefined): Record<string, string> {
    return Object.fromEntries(
        Object.entries(secretEntries(input) ?? {}).filter(
            (entry): entry is [string, string] => typeof entry[1] === 'string'
        )
    )
}

// The dialog types text, so it asks only for a secret stored as text or as a dictionary of text.
export function secretReentryPrompt(
    configuration: SecretReentryConfiguration,
    { key, detail }: InputRefusal,
    source: SecretReentrySource
): SecretReentryPrompt | null {
    const schema = configuration.inputs_schema?.find((s) => s.key === key)
    if (!schema) {
        return null
    }
    const label = schema.label || schema.key
    if (schema.type === 'string') {
        return { key, label, detail, entryKeys: null, source }
    }
    if (schema.type !== 'dictionary') {
        return null
    }
    const entries = textEntries(configuration.inputs?.[key] ?? undefined)
    const entryKeys = Object.keys(entries).filter((entry) => entries[entry] === MASKED_SECRET_VALUE)
    return entryKeys.length ? { key, label, detail, entryKeys, source } : null
}

/** The input to store for an entered secret. A save sends a `secret` input as "keep the stored value", so it drops the flag. */
export function enteredSecretInput(
    input: CyclotronJobInputType | undefined,
    value: SecretReentryValue
): CyclotronJobInputType {
    return { ...input, secret: false, value }
}

