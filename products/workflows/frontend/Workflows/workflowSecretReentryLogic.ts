/** Asks for a workflow step's secret again when the server refuses to keep it, and retries what was refused. */
export const workflowSecretReentryLogic = kea<workflowSecretReentryLogicType>([
    props({} as WorkflowLogicProps),
    key(workflowLogicKey),
    path((key) => ['products', 'workflows', 'frontend', 'Workflows', 'workflowSecretReentryLogic', key]),
    connect((props: WorkflowLogicProps) => ({
        values: [
            workflowLogic(props),
            ['workflow', 'hogFunctionTemplatesById'],
            secretReentryDialogLogic({ dialogKey: workflowSecretReentryDialogKey(props) }),
            ['isOpen', 'prompt', 'currentInput', 'enteredValue'],
        ],
        actions: [
            workflowLogic(props),
            [
                'requestStepSecretReentry',
                'partialSetWorkflowActionConfig',
                'submitWorkflow',
                'publishDraft',
                'saveWorkflowSuccess',
                'saveWorkflowFailure',
            ],
            secretReentryDialogLogic({ dialogKey: workflowSecretReentryDialogKey(props) }),
            ['openSecretReentry', 'cancelSecretReentry', 'confirmSecretReentry', 'closeSecretReentry'],
        ],
    })),
    actions({
        requireSecretReentry: (refusal: StepInputRefusal, source: SecretReentrySource, onContinue: () => void) => ({
            refusal,
            source,
            onContinue,
        }),
    }),
    listeners(({ actions, values, cache: logicCache }) => {
        const cache: WorkflowSecretReentryCache = logicCache
        return {
            requestStepSecretReentry: ({ refusal, source }) => {
                if (source === 'save') {
                    actions.requireSecretReentry(refusal, source, () => actions.submitWorkflow())
                    return
                }
                // The form holds the staged draft, so the entered secret is staged first and then published.
                actions.requireSecretReentry(refusal, source, () => {
                    cache.publishAfterSave = true
                    actions.submitWorkflow()
                })
            },
            saveWorkflowSuccess: () => {
                if (cache.publishAfterSave) {
                    cache.publishAfterSave = false
                    actions.publishDraft()
                }
            },
            saveWorkflowFailure: () => {
                cache.publishAfterSave = false
            },
            requireSecretReentry: ({ refusal, source, onContinue }) => {
                if (values.isOpen) {
                    return
                }
                const step = stepInputs(values.workflow, refusal.stepId, values.hogFunctionTemplatesById)
                const prompt = step && secretReentryPrompt(step.configuration, refusal, source)
                if (!step || !prompt) {
                    // pinned: analytics event name - renaming breaks dashboards
                    posthog.capture('workflow secret reentry unavailable', { source })
                    lemonToast.error('Enter the secret again in the step. Your changes send it to a new address.')
                    return
                }
                cache.onContinue = onContinue
                cache.stepId = refusal.stepId
                actions.openSecretReentry(
                    { ...prompt, label: `${prompt.label} in ${step.name}` },
                    step.configuration.inputs?.[refusal.key]
                )
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflow secret reentry shown', trackingProperties(prompt))
            },
            cancelSecretReentry: () => {
                if (values.prompt) {
                    // pinned: analytics event name - renaming breaks dashboards
                    posthog.capture('workflow secret reentry cancelled', trackingProperties(values.prompt))
                }
                actions.closeSecretReentry()
            },
            confirmSecretReentry: () => {
                const { prompt, enteredValue: value } = values
                const step = cache.stepId
                    ? stepInputs(values.workflow, cache.stepId, values.hogFunctionTemplatesById)
                    : null
                if (!values.isOpen || !prompt || value === null || !step || !cache.stepId) {
                    return
                }
                const inputs = step.configuration.inputs ?? {}
                actions.partialSetWorkflowActionConfig(cache.stepId, {
                    inputs: { ...inputs, [prompt.key]: enteredSecretInput(inputs[prompt.key], value) },
                })
                // pinned: analytics event name - renaming breaks dashboards
                posthog.capture('workflow secret reentry confirmed', trackingProperties(prompt))
                const onContinue = cache.onContinue
                cache.onContinue = undefined
                cache.stepId = undefined
                actions.closeSecretReentry()
                onContinue?.()
            },
        }
    }),
])
