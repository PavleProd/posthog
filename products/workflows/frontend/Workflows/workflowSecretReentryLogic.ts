function trackingProperties(prompt: SecretReentryPrompt): Record<string, string> {
    return { source: prompt.source, kind: prompt.entryKeys ? 'dictionary' : 'single' }
}

function stepInputs(
    workflow: HogFlow,
    stepId: string,
    templates: Record<string, HogFunctionTemplateType>
): { name: string; configuration: Parameters<typeof secretReentryPrompt>[0] } | null {
    const step = workflow.actions.find((action) => action.id === stepId)
    if (!step || !(isFunctionAction(step) || isTriggerFunction(step))) {
        return null
    }
    return {
        name: step.name,
        configuration: {
            inputs_schema: templates[step.config.template_id]?.inputs_schema,
            inputs: step.config.inputs,
        },
    }
}

